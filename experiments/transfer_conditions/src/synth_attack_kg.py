#!/usr/bin/env python3
"""Study S data: synthetic ATT&CK-like clients with planted multi-hop attack patterns.

Every domain uses one schema. Groups employ software, software implements
techniques and runs on assets, campaigns are attributed to groups and use
techniques, techniques target assets, mitigations mitigate techniques, and
techniques form a parent/sub-technique hierarchy. The evaluated relation,
uses(group, technique), is generated by the domain's attack grammar:
  toolkit  : uses(G, T) <- employs(G, S), implements(S, T)
  campaign : uses(G, T) <- attributed-to(C, G), campaign-uses(C, T)
Background relations are drawn independently of the grammar, so both path types
exist in every domain and only the uses facts say which one is predictive.
Background relations carry their own shared hierarchy patterns (sub-techniques
inherit mitigations and targeted assets), as in real ATT&CK.

Clients share no entities. Everything written here is synthetic, not ATT&CK data.
The target always follows the toolkit grammar; sources differ only in grammar and
share one background graph, so the two federation conditions differ in one factor.
"""
import argparse
import json
from collections import Counter
from pathlib import Path

import numpy as np

from common import STUDY, sha256, write_triples

DEFAULT_OUT = STUDY / "data" / "synthetic"
SEED = 20261101
P_MAIN = 0.6  # probability that a grammar-reachable technique is used
SCARCITY = (1 / 32, 1 / 10, 1 / 3, 1.0)  # fractions of the target's uses training pool
TARGET_SIZE = dict(n_groups=80, n_software=200, n_parents=90, n_mitigations=40, n_assets=12)
SOURCE_SIZE = dict(n_groups=150, n_software=375, n_parents=170, n_mitigations=75, n_assets=12)


def make_domain(prefix, seed, grammar, n_groups, n_software, n_parents, n_mitigations, n_assets):
    rng = np.random.default_rng(seed)

    def pick(pool, k):
        return [pool[i] for i in rng.choice(len(pool), size=min(int(k), len(pool)), replace=False)]

    group = [f"{prefix}/group/{i}" for i in range(n_groups)]
    software = [f"{prefix}/software/{i}" for i in range(n_software)]
    asset = [f"{prefix}/asset/{i}" for i in range(n_assets)]
    mitigation = [f"{prefix}/mitigation/{i}" for i in range(n_mitigations)]
    background = set()

    parents, subs = [], {}
    for i in range(n_parents):
        parent = f"{prefix}/technique/{i}"
        parents.append(parent)
        subs[parent] = [f"{parent}.{j}" for j in range(rng.integers(0, 5))]
        background.update((sub, "subtechnique-of", parent) for sub in subs[parent])
    technique = parents + [sub for parent in parents for sub in subs[parent]]

    # Sub-techniques mostly inherit their parent's targeted assets and mitigations.
    for parent in parents:
        parent_assets = pick(asset, 1 + rng.binomial(1, 0.5))
        background.update((parent, "targets", a) for a in parent_assets)
        for sub in subs[parent]:
            own = [a for a in parent_assets if rng.random() < 0.8]
            if rng.random() < 0.2 or not own:
                own += pick(asset, 1)
            background.update((sub, "targets", a) for a in own)
    for m in mitigation:
        for parent in pick(parents, 2 + rng.poisson(1)):
            if rng.random() < 0.9:
                background.add((m, "mitigates", parent))
            background.update((m, "mitigates", sub) for sub in subs[parent] if rng.random() < 0.7)

    implements = {}
    for s in software:
        implements[s] = pick(technique, 3 + rng.poisson(3))
        background.update((s, "implements", t) for t in implements[s])
        background.update((s, "runs-on", a) for a in pick(asset, 1 + rng.binomial(1, 0.5)))

    reach = {"toolkit": {}, "campaign": {}}
    n_campaigns = 0
    for g in group:
        tools = pick(software, 1 + rng.poisson(2))
        background.update((g, "employs", s) for s in tools)
        reach["toolkit"][g] = {t for s in tools for t in implements[s]}
        reach["campaign"][g] = set()
        for _ in range(1 + rng.poisson(1)):
            c = f"{prefix}/campaign/{n_campaigns}"
            n_campaigns += 1
            background.add((c, "attributed-to", g))
            used = pick(technique, 4 + rng.poisson(4))
            background.update((c, "campaign-uses", t) for t in used)
            reach["campaign"][g].update(used)

    # The grammar decides which path explains uses; a little noise is added to every group.
    uses = set()
    for g in group:
        uses.update((g, "uses", t) for t in sorted(reach[grammar][g]) if rng.random() < P_MAIN)
        uses.update((g, "uses", t) for t in pick(technique, rng.poisson(1)))

    def overlap(a, b):
        return sum(len(a[g] & b[g]) for g in group) / max(1, sum(len(a[g] | b[g]) for g in group))

    stats = {
        "grammar": grammar,
        "entities": {"group": n_groups, "software": n_software, "technique": len(technique),
                     "campaign": n_campaigns, "mitigation": n_mitigations, "asset": n_assets},
        "background_relation_counts": dict(sorted(Counter(r for _, r, _ in background).items())),
        "uses_facts": len(uses),
        "mean_toolkit_reach_per_group": float(np.mean([len(reach["toolkit"][g]) for g in group])),
        "mean_campaign_reach_per_group": float(np.mean([len(reach["campaign"][g]) for g in group])),
        "toolkit_campaign_reach_jaccard": overlap(reach["toolkit"], reach["campaign"]),
        "uses_explained_by_toolkit_path": sum(t in reach["toolkit"][g] for g, _, t in uses) / len(uses),
        "uses_explained_by_campaign_path": sum(t in reach["campaign"][g] for g, _, t in uses) / len(uses),
    }
    return sorted(background), sorted(uses), stats


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    out = args.output_root
    if out.exists() and any(out.iterdir()) and not args.overwrite:
        raise FileExistsError(f"{out} is not empty; pass --overwrite to regenerate")

    manifest = {"generator_seed": args.seed, "p_main": P_MAIN, "scarcity_fractions": SCARCITY,
                "target_size": TARGET_SIZE, "source_size": SOURCE_SIZE,
                "synthetic": True, "clients": {}}

    # Target: toolkit grammar; uses facts split into validation, test and a training pool.
    background, uses, stats = make_domain("tgt", args.seed + 2, "toolkit", **TARGET_SIZE)
    order = np.random.default_rng(args.seed + 3).permutation(len(uses))
    uses = [uses[i] for i in order]
    n_valid, n_test = len(uses) // 6, len(uses) // 3
    valid, test, pool = uses[:n_valid], uses[n_valid:n_valid + n_test], uses[n_valid + n_test:]
    stats["split"] = {"valid": len(valid), "test": len(test), "uses_training_pool": len(pool)}
    manifest["clients"]["target"] = stats
    for fraction in SCARCITY:
        n = max(1, round(len(pool) * fraction))
        folder = out / f"target_n{n}"
        write_triples(folder / "train.txt", background + pool[:n])  # nested: smaller pools are prefixes
        if pool[n:]:
            write_triples(folder / "hidden.txt", pool[n:])
        write_triples(folder / "valid.txt", valid)
        write_triples(folder / "test.txt", test)
        manifest["clients"][f"target_n{n}"] = {
            "observed_uses_train": n, "hidden_uses": len(pool) - n,
            "train_triples": len(background) + n,
            "sha256": {f.name: sha256(f) for f in sorted(folder.glob("*.txt"))},
        }

    # Sources: one background graph, two grammars. All source facts are training facts.
    for grammar in ("toolkit", "campaign"):
        background_s, uses_s, stats_s = make_domain("src", args.seed + 1, grammar, **SOURCE_SIZE)
        folder = out / f"source_{grammar}"
        write_triples(folder / "train.txt", background_s + uses_s)
        stats_s["train_triples"] = len(background_s) + len(uses_s)
        stats_s["sha256"] = {"train.txt": sha256(folder / "train.txt")}
        manifest["clients"][f"source_{grammar}"] = stats_s

    out.mkdir(parents=True, exist_ok=True)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
